#!/usr/bin/env python3
"""Plan, and with --apply write, the upgrades that fix known vulnerabilities.

Runs without Claude. Standard library only. Dry run by default: nothing is written without --apply.

    python fix_deps.py [project_dir] [--apply] [--allow-major] [--min-severity low|moderate|high|critical]

For each vulnerable package it picks the lowest version that fixes every advisory with a released fix (as
dep_audit.py reports). Then:
    requirements*.txt  `name==old` becomes `name==new` (extras, markers and comments are kept)
    package.json       the version spec keeps its operator: "^4.17.15" becomes "^4.18.0"
    pyproject.toml     the lower bound is raised: "requests>=2.20" becomes "requests>=2.32.0" (upper bounds kept;
                       if one excludes the fix, the entry is left for a person); Poetry "^2.0" becomes "^2.3.2"
    Cargo.toml         the version requirement is set: serde = "1.0.100" becomes "1.0.180"
For a project with a lockfile (uv.lock, poetry.lock, Cargo.lock, package-lock.json ...) the manifest is edited and
the command that regenerates the lockfile is printed. Transitive packages and other ecosystems get the command to
run with the project's own tool, because a lockfile must be regenerated by that tool, not edited by hand.

Upgrades that cross a major version (or a 0.x minor) are listed but not applied unless --allow-major: they can
break the API. After --apply, regenerate lockfiles and run the project's tests.

Exit codes: 0 nothing to fix or all planned fixes applied, 1 fixes remain (dry run, or skipped/manual ones),
2 setup or network problem.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from dataclasses import dataclass
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import netlib  # noqa: E402
import osv  # noqa: E402
from dep_audit import load_ignore, upgrade_target  # noqa: E402
from lockfiles import Package, normalize, scan  # noqa: E402
from registry import bump_kind, version_key  # noqa: E402

COMMANDS = {
    "PyPI": "pip install \"{name}=={version}\"  (or: uv add / poetry add {name}@{version})",
    "npm": "npm install {name}@{version}  (transitive: add \"overrides\": {{\"{name}\": \"{version}\"}} to package.json)",
    "crates.io": "cargo update -p {name} --precise {version}",
    "Go": "go get {name}@{version} && go mod tidy",
    "Packagist": "composer require {name}:{version}",
    "RubyGems": "bundle update {name} --conservative  (needs a Gemfile constraint that allows {version})",
}


@dataclass
class Plan:
    package: Package
    target: str
    kind: str              # major | minor | patch
    action: str            # edit | manual | skipped-major | no-fix
    file: str = ""
    detail: str = ""


def read_raw(path: Path) -> str:
    """The file's text with its line endings untouched (read_text() would turn CRLF into LF, and writing that back
    would show every line of a Windows file as changed)."""
    with path.open(encoding="utf-8", newline="") as f:
        return f.read()


def edit_requirements(path: Path, name: str, new: str) -> bool:
    text = read_raw(path)
    pattern = re.compile(r"^(\s*)([A-Za-z0-9][A-Za-z0-9._-]*)(\[[^\]]*\])?(\s*===?\s*)([^\s;#\\]+)", re.MULTILINE)
    changed = False

    def repl(m: re.Match) -> str:
        nonlocal changed
        if normalize("PyPI", m.group(2)) != name:
            return m.group(0)
        changed = True
        return f"{m.group(1)}{m.group(2)}{m.group(3) or ''}{m.group(4)}{new}"
    new_text = pattern.sub(repl, text)
    if changed:
        path.write_text(new_text, encoding="utf-8", newline="")
    return changed


def edit_package_json(path: Path, name: str, new: str) -> bool:
    """Change the spec in place in the text (keeps formatting and key order); keep ^ ~ >= operators."""
    text = read_raw(path)
    data = json.loads(text)
    changed = False
    for section in ("dependencies", "devDependencies", "optionalDependencies"):
        spec = (data.get(section) or {}).get(name)
        if not isinstance(spec, str):
            continue
        m = re.match(r"^([\^~]|>=)?\s*v?\d", spec)
        if not m:
            continue  # tags, URLs, workspace: leave alone
        new_spec = (m.group(1) or "") + new
        pattern = re.compile(r'("' + re.escape(name) + r'"\s*:\s*")' + re.escape(spec) + '"')
        text, n = pattern.subn(lambda mm: mm.group(1) + new_spec + '"', text, count=1)
        changed = changed or n > 0
    if changed:
        path.write_text(text, encoding="utf-8", newline="")
    return changed


# After editing a manifest, the lockfile must be regenerated by the project's tool.
RELOCK = {"uv.lock": "uv lock --upgrade-package {name}", "poetry.lock": "poetry lock",
          "pdm.lock": "pdm lock --update-reuse", "Cargo.lock": "cargo update -p {name}",
          "package-lock.json": "npm install", "yarn.lock": "yarn install", "pnpm-lock.yaml": "pnpm install"}


def manifest_for(root: Path, p: Package) -> str:
    """The file fix_deps can edit for this package (relative to root), or '' when only a command can fix it."""
    if not p.direct:
        return ""
    src = Path(p.source)
    if re.search(r"(^|/)requirements[\w.-]*\.txt$", p.source) or src.name in ("package.json", "pyproject.toml",
                                                                             "Cargo.toml"):
        return p.source
    sibling = {"npm": "package.json", "PyPI": "pyproject.toml", "crates.io": "Cargo.toml"}.get(p.ecosystem)
    if sibling and src.name in RELOCK and (root / src.parent / sibling).is_file():
        candidate = root / src.parent / sibling
        if p.ecosystem == "npm" or _lists(candidate, p):
            return (src.parent / sibling).as_posix()
    return ""


def _lists(manifest: Path, p: Package) -> bool:
    from lockfiles import MANIFESTS
    try:
        return any(m.name == p.name for m in MANIFESTS[manifest.name](manifest, manifest.name))
    except (OSError, ValueError, KeyError):
        return False


def _rewrite_spec(spec: str, new: str) -> str | None:
    """A PEP 440 specifier with its lower bound raised to `new`, or None if an upper bound excludes `new`."""
    clauses = [c.strip() for c in spec.split(",") if c.strip()]
    out, has_lower = [], False
    for c in clauses:
        m = re.match(r"^(===?|>=|~=|>|<=|<|!=)\s*(.+)$", c)
        if not m:
            out.append(c)
            continue
        op, ver = m.groups()
        if op in ("==", "===", ">=", "~=", ">"):
            out.append(f"{'>=' if op == '>' else op}{new}")
            has_lower = True
        elif op in ("<", "<=") and (version_key(new) >= version_key(ver) if op == "<" else version_key(new) > version_key(ver)):
            return None
        else:
            out.append(c)
    if not has_lower:
        out.insert(0, f">={new}")
    return ",".join(out)


def edit_pyproject(path: Path, name: str, new: str) -> bool:
    """Raise the lower bound of `name` in PEP 508 strings ("requests>=2.25") and Poetry tables (requests = "^2.25")."""
    text = read_raw(path)
    changed = False

    def pep508(m: re.Match) -> str:
        nonlocal changed
        if normalize("PyPI", m.group(2)) != name:
            return m.group(0)
        old_spec = (m.group(4) or "").strip()
        if old_spec and not re.match(r"^[<>=!~]", old_spec):
            return m.group(0)  # not a dependency string (a URL, a plain word ...)
        spec = _rewrite_spec(old_spec, new)
        if spec is None:
            return m.group(0)
        changed = True
        return f'{m.group(1)}{m.group(2)}{m.group(3) or ""}{spec}{m.group(5) or ""}{m.group(6)}{m.group(1)}'
    # "name[extras] spec ; marker" inside one pair of quotes; the marker may contain the other quote character
    # (one line only: a closing quote followed by the next line must never pair up as a string)
    text = re.sub(r"""(["'])[ \t]*([A-Za-z0-9][A-Za-z0-9._-]*)[ \t]*(\[[^\]\n]*\])?[ \t]*((?:(?!\1)[^;\n])*?)"""
                  r"""([ \t]*;(?:(?!\1)[^\n])*?)?([ \t]*)\1""", pep508, text)

    def poetry(m: re.Match) -> str:
        nonlocal changed
        if normalize("PyPI", m.group(1)) != name:
            return m.group(0)
        changed = True
        return f"{m.group(1)}{m.group(2)}{m.group(3) or ''}{new}{m.group(4)}"
    text = re.sub(r'^([A-Za-z0-9][A-Za-z0-9._-]*)(\s*=\s*(?:\{[^}\n]*version\s*=\s*)?")([\^~]|>=|==)?[^"]*(")',
                  poetry, text, flags=re.MULTILINE)
    if changed:
        path.write_text(text, encoding="utf-8", newline="")
    return changed


def edit_cargo_toml(path: Path, name: str, new: str) -> bool:
    """Set the version requirement of `name` (keeps ^ ~ = operators): serde = "1.0" / serde = { version = "1.0" }."""
    text = read_raw(path)
    pattern = re.compile(r'^(' + re.escape(name) + r'\s*=\s*(?:\{[^}\n]*version\s*=\s*)?")([\^~=]|>=)?[^"]*(")',
                         re.MULTILINE)
    new_text, n = pattern.subn(lambda m: f"{m.group(1)}{m.group(2) or ''}{new}{m.group(3)}", text)
    if n:
        path.write_text(new_text, encoding="utf-8", newline="")
    return n > 0


EDITORS = {"package.json": edit_package_json, "pyproject.toml": edit_pyproject, "Cargo.toml": edit_cargo_toml}


def same_major_target(finding: osv.Finding) -> tuple[str, int]:
    """The lowest version on the current major line (0.x: the current minor line) that fixes as many advisories
    as that line can fix, and how many it fixes. ('', 0) when no fix exists on the line."""
    current = finding.package.version
    cur = version_key(current)[0]
    line = cur[:2] if cur[0] == 0 else cur[:1]
    fixes = []
    for v in finding.vulns:
        same = [x for x in v.fixed if version_key(x)[0][:len(line)] == line and version_key(x) > version_key(current)]
        if same:
            fixes.append(min(same, key=version_key))
    if not fixes:
        return "", 0
    return max(fixes, key=version_key), len(fixes)


def plan_fixes(root: Path, findings: list[osv.Finding], allow_major: bool) -> list[Plan]:
    plans = []
    for f in findings:
        p = f.package
        target, _unfixed = upgrade_target(f)
        if not target:
            plans.append(Plan(p, "", "", "no-fix", detail="no fixed version released yet"))
            continue
        kind = bump_kind(p.version, target) or "patch"
        manifest = manifest_for(root, p)
        if kind == "major" and not allow_major:
            detail = "crosses a major version: read the changelog, then rerun with --allow-major"
            same, fixed_n = same_major_target(f)
            if same:
                detail += f". Staying on the current major, {same} fixes {fixed_n} of {len(f.vulns)}"
            plans.append(Plan(p, target, kind, "skipped-major", detail=detail))
        elif manifest:
            relock = RELOCK.get(Path(p.source).name, "").format(name=p.name)
            plans.append(Plan(p, target, kind, "edit", file=manifest,
                              detail=f"then: {relock}" if relock else ""))
        else:
            cmd = COMMANDS.get(p.ecosystem, "upgrade {name} to {version}").format(name=p.name, version=target)
            plans.append(Plan(p, target, kind, "manual", detail=cmd))
    return plans


def main(argv: list[str] | None = None) -> int:
    netlib.force_utf8_output()
    ap = argparse.ArgumentParser(description="Plan or apply upgrades that fix known vulnerabilities.")
    ap.add_argument("project", nargs="?", default=".", help="project folder (default: .)")
    ap.add_argument("--apply", action="store_true", help="write the edits (default: dry run)")
    ap.add_argument("--allow-major", action="store_true", help="also apply upgrades across a major version")
    ap.add_argument("--min-severity", default="low", choices=osv.SEVERITY_ORDER[1:],
                    help="only fix packages whose worst finding is at least this (default low)")
    a = ap.parse_args(argv)

    root = Path(a.project).resolve()
    result = scan(root)
    if not result.files:
        print(f"No dependency files found in {root}.", file=sys.stderr)
        return 2
    try:
        findings = osv.audit(result.packages, load_ignore(root))
    except netlib.NetError as e:
        print(f"ERROR: {e}", file=sys.stderr)
        return 2
    threshold = osv.SEVERITY_ORDER.index(a.min_severity)
    findings = [f for f in findings if osv.SEVERITY_ORDER.index(f.worst) >= threshold or f.worst == "unknown"]
    if not findings:
        print(f"{root.name}: no known vulnerabilities to fix.")
        return 0

    plans = plan_fixes(root, findings, a.allow_major)
    applied, failed = [], []
    for pl in plans:
        if pl.action != "edit" or not a.apply:
            continue
        path = root / pl.file
        editor = edit_requirements if path.name.endswith(".txt") else EDITORS[path.name]
        ok = editor(path, pl.package.name, pl.target)
        (applied if ok else failed).append(pl)
        if not ok:
            pl.action, pl.detail = "manual", f"could not find {pl.package.name} in {pl.file}; " + \
                COMMANDS.get(pl.package.ecosystem, "").format(name=pl.package.name, version=pl.target)

    mode = "applied" if a.apply else "dry run, nothing written (use --apply)"
    print(f"{root.name}: {len(plans)} vulnerable package(s)  |  {mode}\n")
    groups = [("edit", "Edits" if a.apply else "Would edit"), ("manual", "Run with the project's tool"),
              ("skipped-major", "Not applied: major upgrade"), ("no-fix", "No fix available")]
    for action, title in groups:
        rows = [pl for pl in plans if pl.action == action]
        if not rows:
            continue
        print(f"{title}:")
        for pl in rows:
            p = pl.package
            arrow = f"{p.version} -> {pl.target} ({pl.kind})" if pl.target else p.version
            where = f"  in {pl.file}" if pl.file else ""
            print(f"  {p.name} {arrow}  [{p.ecosystem}, worst {next(f.worst for f in findings if f.package == p)}]{where}")
            if pl.detail:
                print(f"      {pl.detail}")
        print()
    if applied:
        print("Next: regenerate lockfiles (pip-compile / uv lock / npm install ...) and run the project's tests, "
              "then dep_audit.py again.")
    remaining = [pl for pl in plans if pl.action != "edit" or not a.apply]
    return 1 if remaining else 0


if __name__ == "__main__":
    sys.exit(main())
