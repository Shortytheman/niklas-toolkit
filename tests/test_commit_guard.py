import io
import json
import subprocess
import sys

import pytest

from conftest import ROOT

sys.path.insert(0, str(ROOT / "packs" / "core" / "scripts"))
import commit_guard  # noqa: E402

# Built at run time so that no real-looking token is ever written into this repository.
GH_TOKEN = "gh" + "p_" + "aB3dE5fG7hJ9kL1mN3pQ5rS7tU9vW1xY3zA5"
AWS_KEY = "AK" + "IA" + "QWERTYUIOPASDFGH"


def git(repo, *args):
    return subprocess.run(["git", "-c", "user.name=t", "-c", "user.email=t@example.com",
                           "-c", "core.autocrlf=false", *args], cwd=repo, check=True, capture_output=True, text=True)


@pytest.fixture
def repo(tmp_path, monkeypatch):
    monkeypatch.setenv("TOOLKIT_HOME", str(tmp_path / "home"))
    monkeypatch.delenv("TOOLKIT_COMMIT_GUARD", raising=False)
    r = tmp_path / "repo"
    r.mkdir()
    git(r, "init", "-q")
    (r / "app.py").write_text("print('hi')\n", encoding="utf-8")
    git(r, "add", ".")
    git(r, "commit", "-q", "-m", "first")
    return r


def hook(command, cwd, monkeypatch, capsys):
    event = {"tool_name": "Bash", "tool_input": {"command": command}, "cwd": str(cwd)}
    monkeypatch.setattr(sys, "stdin", io.StringIO(json.dumps(event)))
    code = commit_guard.main([])
    return code, capsys.readouterr().err


def test_staged_secret_blocks_commit(repo, monkeypatch, capsys):
    (repo / "app.py").write_text(f"print('hi')\ntoken = '{GH_TOKEN}'\n", encoding="utf-8")
    git(repo, "add", "app.py")
    code, err = hook('git commit -m "add token"', repo, monkeypatch, capsys)
    assert code == 2
    assert "secret   app.py:2: GitHub token ghp_aB..." in err and GH_TOKEN not in err   # masked


def test_add_in_same_command_scans_unstaged_and_new_files(repo, monkeypatch, capsys):
    (repo / "config.py").write_text(f"KEY = '{AWS_KEY}'\n", encoding="utf-8")         # untracked, not staged
    (repo / ".env").write_text("DEBUG=1\n", encoding="utf-8")
    code, err = hook("cd . && git add -A && git commit -q -m 'wip'", repo, monkeypatch, capsys)
    assert code == 2 and "config.py:1: AWS access key" in err and "file     .env:" in err
    # Without the add, nothing is staged: nothing to block.
    assert hook("git commit -m 'wip'", repo, monkeypatch, capsys)[0] == 0


def test_allow_mark_safe_files_and_allow_paths(repo, monkeypatch, capsys):
    (repo / "fixture.py").write_text(f"T = '{GH_TOKEN}'  # commit-guard: allow\n", encoding="utf-8")
    (repo / ".env.example").write_text("KEY=\n", encoding="utf-8")
    (repo / "tests").mkdir()
    (repo / "tests" / "data.txt").write_text(AWS_KEY + "\n", encoding="utf-8")
    (repo / "toolkit.json").write_text(json.dumps({"commit_guard": {"allow_paths": ["tests/*"]}}),
                                       encoding="utf-8")
    git(repo, "add", ".")
    assert hook("git commit -m ok", repo, monkeypatch, capsys) == (0, "")


def test_forbidden_message_from_user_config(repo, monkeypatch, capsys, tmp_path):
    home = tmp_path / "home"
    home.mkdir()
    (home / "config.json").write_text(json.dumps({"commit_guard": {"forbid": ["(?i)co-authored-by:.*bot"]}}),
                                      encoding="utf-8")
    (repo / "app.py").write_text("print('changed')\n", encoding="utf-8")
    git(repo, "add", ".")
    code, err = hook('git commit -q -m "Fix" -m "Co-Authored-By: Some Bot <b@x>"', repo, monkeypatch, capsys)
    assert code == 2 and "message  commit message: contains 'Co-Authored-By: Some Bot'" in err
    assert "from user config" in err
    assert hook('git commit -m "Fix the bot detection"', repo, monkeypatch, capsys)[0] == 0
    code, err = hook("git commit -am 'x\n\nco-authored-by: a bot'", repo, monkeypatch, capsys)
    assert code == 2


def test_push_checks_unpushed_commits_and_tags(repo, monkeypatch, capsys, tmp_path):
    remote = tmp_path / "remote.git"
    git(tmp_path, "init", "-q", "--bare", str(remote))
    git(repo, "remote", "add", "origin", str(remote))
    git(repo, "push", "-q", "origin", "HEAD:refs/heads/main")
    git(repo, "fetch", "-q", "origin")
    (repo / "toolkit.json").write_text(json.dumps({"commit_guard": {"forbid": ["generated by robot"]}}),
                                       encoding="utf-8")
    git(repo, "add", ".")
    git(repo, "commit", "-q", "-m", "Config\n\ngenerated by robot")
    git(repo, "tag", "-a", "v1", "-m", "release, generated by robot")
    code, err = hook("git push origin HEAD v1", repo, monkeypatch, capsys)
    assert code == 2
    assert "commit " in err and "tag v1" in err and "ask the user before rewording" in err

    git(repo, "commit", "-q", "--amend", "-m", "Config")
    git(repo, "tag", "-d", "v1")
    (repo / "keys.py").write_text(f"K = '{AWS_KEY}'\n", encoding="utf-8")
    git(repo, "add", ".")
    git(repo, "commit", "-q", "-m", "keys")
    code, err = hook("git push", repo, monkeypatch, capsys)
    assert code == 2 and "keys.py:1: AWS access key" in err


def test_ignores_other_commands_and_fails_open(repo, monkeypatch, capsys):
    assert hook("git status && echo commit", repo, monkeypatch, capsys) == (0, "")
    assert hook("git log --grep commit", repo, monkeypatch, capsys) == (0, "")
    assert hook("git commit -m x", repo.parent, monkeypatch, capsys) == (0, "")      # not a repository
    assert hook("git commit -m \"$(cat <<'EOF'\nunbalanced", repo, monkeypatch, capsys)[0] == 0
    monkeypatch.setenv("TOOLKIT_COMMIT_GUARD", "off")
    (repo / "app.py").write_text(GH_TOKEN + "\n", encoding="utf-8")
    git(repo, "add", ".")
    assert hook("git commit -m x", repo, monkeypatch, capsys) == (0, "")


def test_segments_and_messages():
    assert commit_guard.segments("git add -A && git commit -m 'a; b'\ngit push") == [
        ["git", "add", "-A"], ["git", "commit", "-m", "a; b"], ["git", "push"]]
    assert commit_guard.git_action(["git", "-C", "sub", "commit", "-m", "x"]) == ("commit", ["-m", "x"], "sub")
    assert commit_guard.commit_messages(["-q", "-m", "one", "--message=two", "-mthree", "-am", "four"], ROOT) == [
        "one", "two", "three", "four"]
